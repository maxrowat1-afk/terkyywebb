const missing = new Set();
html = html.replace(
  /<i\s+data-lucide="([^"]+)"([^>]*)><\/i>/g,
  (_, name, attrs) => {
    const inner = paths[name];
    if (!inner) {
      missing.add(name);
      return _;
    }
    const extra = attrs.trim();
    const cls = extra ? ` ${extra.trim()}` : "";
    // attrs already include class="..."
    return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"${cls} aria-hidden="true">${inner}</svg>`;
  },
);

if (missing.size) {
  throw new Error("Missing Lucide paths: " + [...missing].join(", "));
}

html = html.replace(
  /\s*<script src="https:\/\/unpkg.com\/lucide@latest"><\/script>\n/,
  "\n",
);
